from __future__ import annotations

import ast
import json
from datetime import datetime, timezone

import pytest

from agentreplay.span import Span
from agentreplay.testgen import fixture as fixture_module
from agentreplay.testgen.fixture import (
    FixtureData,
    build_fixture_data,
    generate_fixture,
    generate_fixture_from_file,
    load_fixture_module,
    render_fixture_module,
    write_fixture_module,
)


def _span(
    *,
    span_id: str,
    span_type: str,
    name: str,
    input: dict,
    output=None,
    parent_id=None,
    started_at: datetime,
    run_id: str = "run-1",
) -> dict:
    return Span(
        id=span_id,
        run_id=run_id,
        parent_id=parent_id,
        type=span_type,
        name=name,
        input=input,
        output=output,
        error=None,
        started_at=started_at,
        duration_ms=1.0,
        fingerprint=f"fp-{span_id}",
    ).to_dict()


T0 = datetime(2026, 1, 1, 0, 0, 0, tzinfo=timezone.utc)
T1 = datetime(2026, 1, 1, 0, 0, 1, tzinfo=timezone.utc)
T2 = datetime(2026, 1, 1, 0, 0, 2, tzinfo=timezone.utc)


# --- build_fixture_data ------------------------------------------------------


def test_recorded_input_is_the_earliest_root_spans_input():
    root_first = _span(
        span_id="a", span_type="llm", name="anthropic.messages.create",
        input={"job_posting": "hi"}, started_at=T0,
    )
    root_second = _span(
        span_id="b", span_type="llm", name="anthropic.messages.create",
        input={"job_posting": "should not be picked"}, started_at=T1,
    )
    nested = _span(
        span_id="c", span_type="tool", name="search",
        input={"args": [], "kwargs": {}}, parent_id="a", started_at=T0,
    )

    data = build_fixture_data("run-1", [root_second, root_first, nested])

    assert data.run_id == "run-1"
    assert data.recorded_input == {"job_posting": "hi"}


def test_recorded_input_falls_back_to_first_span_when_every_span_has_a_parent():
    only_span = _span(
        span_id="a", span_type="tool", name="search",
        input={"args": ["x"], "kwargs": {}}, parent_id="ghost-parent", started_at=T0,
    )

    data = build_fixture_data("run-1", [only_span])
    assert data.recorded_input == {"args": ["x"], "kwargs": {}}


def test_recorded_input_is_none_for_empty_run():
    data = build_fixture_data("run-1", [])
    assert data.recorded_input is None
    assert data.tool_spans == []


def test_tool_spans_filters_to_type_tool_only_in_chronological_order():
    llm_span = _span(
        span_id="a", span_type="llm", name="anthropic.messages.create",
        input={"messages": []}, started_at=T0,
    )
    tool_span_2 = _span(
        span_id="c", span_type="tool", name="search",
        input={"args": ["second"], "kwargs": {}}, started_at=T2,
    )
    tool_span_1 = _span(
        span_id="b", span_type="tool", name="search",
        input={"args": ["first"], "kwargs": {}}, started_at=T1,
    )

    data = build_fixture_data("run-1", [tool_span_2, llm_span, tool_span_1])

    assert [s["id"] for s in data.tool_spans] == ["b", "c"]
    assert all(s["type"] == "tool" for s in data.tool_spans)


def test_build_fixture_data_accepts_span_objects_directly():
    span = Span(
        id="a", run_id="run-1", parent_id=None, type="tool", name="search",
        input={"args": [], "kwargs": {}}, output="ok", error=None,
        started_at=T0, duration_ms=1.0, fingerprint="fp-a",
    )
    data = build_fixture_data("run-1", [span])
    assert data.tool_spans[0]["id"] == "a"


def test_build_fixture_data_rejects_unknown_span_shape():
    with pytest.raises(TypeError, match="cannot use"):
        build_fixture_data("run-1", [object()])


# --- render_fixture_module / write_fixture_module ---------------------------


def test_render_fixture_module_is_valid_python_and_round_trips(tmp_path):
    data = FixtureData(
        run_id="run-xyz",
        recorded_input={"job_posting": "hi", "n": 1, "pair": (1, 2)},
        tool_spans=[
            _span(
                span_id="t1", span_type="tool", name="search",
                input={"args": ["q"], "kwargs": {}}, output=["a", "b"], started_at=T0,
            )
        ],
    )

    source = render_fixture_module(data)
    ast.parse(source)  # raises SyntaxError if the generated module is bad
    assert "Auto-generated by `agentreplay`" in source
    assert "Do NOT edit by hand" in source

    written_path = write_fixture_module(data, tmp_path / "nested" / "fixture_run_xyz.py")
    assert written_path.is_file()

    loaded = load_fixture_module(written_path)
    assert loaded.run_id == data.run_id
    assert loaded.recorded_input == data.recorded_input
    assert loaded.tool_spans == data.tool_spans


def test_write_fixture_module_warns_on_overwrite_with_different_content(tmp_path, capsys):
    path = tmp_path / "fixture_run_xyz.py"
    path.write_text("# hand-edited, not what generation would produce\n")

    data = FixtureData(run_id="run-xyz", recorded_input={"x": 1}, tool_spans=[])
    write_fixture_module(data, path)

    assert "overwriting existing file with different content" in capsys.readouterr().err


def test_write_fixture_module_no_warning_when_content_is_identical(tmp_path, capsys):
    data = FixtureData(run_id="run-xyz", recorded_input={"x": 1}, tool_spans=[])
    path = tmp_path / "fixture_run_xyz.py"
    write_fixture_module(data, path)
    capsys.readouterr()  # discard the first write (file didn't exist yet)

    write_fixture_module(data, path)  # regenerating identical content
    assert capsys.readouterr().err == ""


def test_write_fixture_module_no_warning_for_a_new_file(tmp_path, capsys):
    data = FixtureData(run_id="run-xyz", recorded_input={"x": 1}, tool_spans=[])
    write_fixture_module(data, tmp_path / "fixture_run_xyz.py")
    assert capsys.readouterr().err == ""


def test_load_fixture_module_missing_file_raises():
    with pytest.raises(FileNotFoundError):
        load_fixture_module("/definitely/not/a/real/path/fixture.py")


# --- generate_fixture / generate_fixture_from_file --------------------------


def test_generate_fixture_fetches_and_writes(monkeypatch, tmp_path):
    tool_span = _span(
        span_id="t1", span_type="tool", name="search",
        input={"args": ["q"], "kwargs": {}}, output="result", started_at=T1,
    )
    root_span = _span(
        span_id="r1", span_type="llm", name="anthropic.messages.create",
        input={"job_posting": "hi"}, started_at=T0,
    )

    def fake_fetch_run(run_id, *, endpoint, api_key, timeout):
        assert run_id == "run-123"
        assert endpoint == "http://localhost:8000"
        assert api_key == "test-key"
        return {"id": run_id, "spans": [tool_span, root_span]}

    monkeypatch.setattr(fixture_module, "fetch_run", fake_fetch_run)
    output_path = tmp_path / "fixture_run_123.py"

    data = generate_fixture(
        "run-123", output_path, endpoint="http://localhost:8000", api_key="test-key"
    )

    assert data.run_id == "run-123"
    assert data.recorded_input == {"job_posting": "hi"}
    assert output_path.is_file()
    loaded = load_fixture_module(output_path)
    assert loaded.recorded_input == {"job_posting": "hi"}
    assert len(loaded.tool_spans) == 1


def test_generate_fixture_propagates_trace_fetch_error(monkeypatch, tmp_path):
    from agentreplay.replay.exceptions import TraceFetchError

    def fake_fetch_run(*args, **kwargs):
        raise TraceFetchError("run-x", "404 not found")

    monkeypatch.setattr(fixture_module, "fetch_run", fake_fetch_run)

    with pytest.raises(TraceFetchError):
        generate_fixture(
            "run-x", tmp_path / "out.py", endpoint="http://x", api_key="k"
        )


def test_generate_fixture_from_file_loads_local_trace(tmp_path):
    tool_span = _span(
        span_id="t1", span_type="tool", name="search",
        input={"args": ["q"], "kwargs": {}}, output="result", started_at=T0,
    )
    trace_file = tmp_path / "trace.json"
    trace_file.write_text(json.dumps({"id": "run-from-file", "spans": [tool_span]}))
    output_path = tmp_path / "fixture.py"

    data = generate_fixture_from_file(trace_file, output_path)

    assert data.run_id == "run-from-file"
    assert output_path.is_file()
    loaded = load_fixture_module(output_path)
    assert len(loaded.tool_spans) == 1


def test_generate_fixture_from_file_falls_back_to_path_as_run_id(tmp_path):
    trace_file = tmp_path / "trace.json"
    trace_file.write_text(json.dumps({"spans": []}))
    output_path = tmp_path / "fixture.py"

    data = generate_fixture_from_file(trace_file, output_path)
    assert data.run_id == str(trace_file)
