

from __future__ import annotations

import importlib.util
import pprint
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable, List, Union

from ..replay.loader import fetch_run, load_run_from_file
from ._fileio import warn_if_overwriting_different_content


def _coerce_span(raw: Any) -> dict:
    """Accept a `Span`, a `Span.to_dict()` dict, or an ingest-API span dict.

    Mirrors `agentreplay/replay/store.py`'s `_coerce_span` — not imported
    from there directly (that one's private to the replay matcher); two
    lines of duplication keeps `testgen` decoupled from `replay`'s
    internals rather than reaching into another module's underscore-prefixed
    helper.
    """
    if isinstance(raw, dict):
        return raw
    to_dict = getattr(raw, "to_dict", None)
    if callable(to_dict):
        return to_dict()
    raise TypeError(f"cannot use {type(raw)!r} as a recorded span")


def _find_recorded_input(ordered_spans: List[dict]) -> Any:
    """The recorded input, per this module's documented convention.

    `ordered_spans` must already be sorted chronologically (lexical
    `started_at` sort, same convention `replay/store.py` uses). Falls back
    to the overall first span if every span somehow has a parent (defensive
    — shouldn't happen for a real run), and to `None` if there are no spans.
    """
    for span in ordered_spans:
        if span.get("parent_id") is None:
            return span.get("input")
    return ordered_spans[0].get("input") if ordered_spans else None


@dataclass
class FixtureData:


    run_id: str
    recorded_input: Any
    tool_spans: List[dict] = field(default_factory=list)


def build_fixture_data(run_id: str, spans: Iterable[Any]) -> FixtureData:
    """Pure function: a run's full span list -> the chunk 4.1 fixture data.

    Accepts the same three shapes `RecordedRun` does (`Span`,
    `Span.to_dict()` dict, ingest-API dict) so it's usable directly in tests
    without going through `generate_fixture()`'s network/file-loading paths.
    """
    coerced = [_coerce_span(s) for s in spans]
    coerced.sort(key=lambda s: s.get("started_at") or "")
    tool_spans = [s for s in coerced if s.get("type") == "tool"]
    return FixtureData(
        run_id=run_id,
        recorded_input=_find_recorded_input(coerced),
        tool_spans=tool_spans,
    )


_MODULE_TEMPLATE = '''\
"""Auto-generated by `agentreplay` from run {run_id!r}.

Do NOT edit by hand -- regenerate from the run instead. Committed to your
repo so a generated pytest file has no dependency on the ingest API being
reachable at test time.
"""
from __future__ import annotations

RUN_ID = {run_id!r}

# The recorded input to the agent entrypoint for this run -- see
# `agentreplay/testgen/fixture.py` module docstring for the exact "which
# span counts as the input" convention.
RECORDED_INPUT = {recorded_input}

# Every `type="tool"` span recorded for this run, in original order. Pass
# this straight into `agentreplay.replay.mock_tools_mode()` to serve these
# exact tool call/response pairs instead of running the real tool code.
TOOL_SPANS = {tool_spans}
'''


def _format_literal(value: Any) -> str:
    return pprint.pformat(value, indent=4, width=88, sort_dicts=False)


def render_fixture_module(data: FixtureData) -> str:
    """Render `data` as Python source for a self-contained fixture module."""
    return _MODULE_TEMPLATE.format(
        run_id=data.run_id,
        recorded_input=_format_literal(data.recorded_input),
        tool_spans=_format_literal(data.tool_spans),
    )


def write_fixture_module(data: FixtureData, path: Union[str, Path]) -> Path:
    """Render and write `data` to `path`, creating parent directories as needed.

    Warns to stderr (never blocks) if `path` already exists with different
    content (Day 4 audit: clobber-protection pending, resolved).

    Returns the resolved `Path` written to.
    """
    file_path = Path(path)
    file_path.parent.mkdir(parents=True, exist_ok=True)
    source = render_fixture_module(data)
    warn_if_overwriting_different_content(file_path, source)
    file_path.write_text(source)
    return file_path


def generate_fixture(
    run_id: str,
    output_path: Union[str, Path],
    *,
    endpoint: str,
    api_key: str,
    timeout: float = 30.0,
) -> FixtureData:
    """Fetch `run_id` from the ingest API, build and write its fixture module.

    The chunk 4.1 capstone, analogous to `agentreplay.replay.replay_run()`
    (chunk 3.4): same `fetch_run()` loader, same `TraceFetchError` contract
    on failure (bad run_id/credentials/network).
    """
    data = fetch_run(run_id, endpoint=endpoint, api_key=api_key, timeout=timeout)
    fixture = build_fixture_data(run_id, data.get("spans", []))
    write_fixture_module(fixture, output_path)
    return fixture


def generate_fixture_from_file(
    trace_file: Union[str, Path], output_path: Union[str, Path]
) -> FixtureData:
    """Load a trace from a local JSON file, build and write its fixture module.

    Offline equivalent of `generate_fixture()` — mirrors
    `agentreplay.replay.replay_run_from_file()`'s credential-free path. No
    `endpoint`/`api_key` needed at all.
    """
    data = load_run_from_file(trace_file)
    run_id = data.get("id") or str(trace_file)
    fixture = build_fixture_data(run_id, data.get("spans", []))
    write_fixture_module(fixture, output_path)
    return fixture


def load_fixture_module(path: Union[str, Path]) -> FixtureData:
    """Import an already-generated fixture `.py` file and read it back.

    Mainly for round-trip verification/tooling (e.g. confirming a generated
    fixture matches the run it came from) — a generated pytest file is
    expected to just `import` the fixture module directly by its normal
    module path, not go through this.
    """
    file_path = Path(path)
    if not file_path.is_file():
        raise FileNotFoundError(f"no fixture module at '{file_path}'")

    spec = importlib.util.spec_from_file_location(file_path.stem, file_path)
    if spec is None or spec.loader is None:
        raise ImportError(f"could not load fixture module '{file_path}'")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    return FixtureData(
        run_id=getattr(module, "RUN_ID", str(file_path)),
        recorded_input=getattr(module, "RECORDED_INPUT", None),
        tool_spans=getattr(module, "TOOL_SPANS", []),
    )
