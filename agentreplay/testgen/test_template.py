

from __future__ import annotations

import re
from pathlib import Path
from typing import Optional, Union

from ._fileio import warn_if_overwriting_different_content


def slugify_run_id(run_id: str) -> str:
    """A valid Python identifier derived from `run_id` (used in filenames/test names)."""
    slug = re.sub(r"[^0-9a-zA-Z_]", "_", run_id)
    if slug and slug[0].isdigit():
        slug = f"_{slug}"
    return slug or "unknown"


def _render_rationale_comment(rationale: Optional[str]) -> str:
    cleaned = (rationale or "").strip()
    if not cleaned:
        return "# (no rationale provided)"
    lines = [line.strip() for line in cleaned.splitlines() if line.strip()]
    return "\n".join(f"# {line}" for line in lines) or "# (no rationale provided)"


_TEST_TEMPLATE_NO_SPEC = '''\
"""Auto-generated regression test for run {run_id!r} (CLAUDE.md §4 chunk 4.2).

Do NOT edit by hand -- regenerate instead. Every recorded tool call is
mocked from the fixture module; the LLM call(s) are NOT mocked (Mode B --
this test should keep catching regressions as your agent's prompts/model
change, not just replay the exact original response).
"""
from __future__ import annotations

from agentreplay.replay import mock_tools_mode, resolve_entrypoint
from agentreplay.testgen.entrypoint import call_entrypoint_with_input
from {fixture_module} import RECORDED_INPUT, TOOL_SPANS

ENTRYPOINT = {entrypoint!r}


def test_run_{run_id_slug}():
    func = resolve_entrypoint(ENTRYPOINT)
    with mock_tools_mode(TOOL_SPANS):
        result = call_entrypoint_with_input(func, RECORDED_INPUT)

    # TODO(agentreplay): no assertion spec yet for this run -- run chunk
    # 4.3's `POST /v1/runs/{{run_id}}/assertion-spec` and regenerate this
    # file to get real assertions (CLAUDE.md §4 chunk 4.4). For now this
    # test only proves the recorded scenario re-runs under tool mocking
    # without an unhandled exception or replay divergence.
    assert True
'''


_TEST_TEMPLATE_WITH_SPEC = '''\
"""Auto-generated regression test for run {run_id!r} (CLAUDE.md §4 chunks 4.2+4.4+4.7).

Do NOT edit by hand -- regenerate instead. Every recorded tool call is
mocked from the fixture module; the LLM call(s) are NOT mocked (Mode B --
this test should keep catching regressions as your agent's prompts/model
change, not just replay the exact original response).
"""
from __future__ import annotations

from agentreplay.replay import mock_tools_mode, resolve_entrypoint
from agentreplay.testgen import assertions
from agentreplay.testgen.entrypoint import call_entrypoint_with_input
from {fixture_module} import RECORDED_INPUT, TOOL_SPANS

ENTRYPOINT = {entrypoint!r}

# Assertion spec generated by Sonnet from the original failure's diagnosis
# (CLAUDE.md §4 chunk 4.3) -- rationale for why these specific checks:
{rationale_comment}
MUST_CALL_TOOLS = {must_call_tools!r}
MUST_NOT_CALL_TOOLS = {must_not_call_tools!r}
MAX_STEPS = {max_steps!r}
NO_EXCEPTION = {no_exception!r}
OUTPUT_CHECKS = {output_checks!r}
# Semantic tier (CLAUDE.md §4 chunk 4.7) -- an LLM-judge rubric for output
# CONTENT, layered on top of the structural checks above. None if this
# failure is already fully captured by them.
SEMANTIC_RUBRIC = {semantic_rubric!r}


def test_run_{run_id_slug}():
    func = resolve_entrypoint(ENTRYPOINT)

    exception = None
    result = None
    with mock_tools_mode(TOOL_SPANS) as tool_run:
        try:
            result = call_entrypoint_with_input(func, RECORDED_INPUT)
        except Exception as exc:  # noqa: BLE001 -- captured for NO_EXCEPTION, not silenced
            exception = exc

    if NO_EXCEPTION:
        assertions.assert_no_exception(exception)
    assertions.assert_must_call_tools(tool_run, MUST_CALL_TOOLS)
    assertions.assert_must_not_call_tools(tool_run, MUST_NOT_CALL_TOOLS)
    assertions.assert_max_steps(tool_run, MAX_STEPS)
    assertions.assert_output_checks(result, OUTPUT_CHECKS)
    assertions.assert_semantic(result, SEMANTIC_RUBRIC)
'''


def render_test_module(
    *, fixture_module: str, entrypoint: str, run_id: str, assertion_spec: Optional[dict] = None
) -> str:
    """Render a pytest file's source for `run_id`.

    `entrypoint` is a `"module.path:function_name"` spec, the same
    convention `agentreplay.replay.resolve_entrypoint()` parses — it's
    embedded as a string literal in the rendered file and resolved at test
    *run* time, not at generation time (so generating a test never imports
    the user's agent module). `fixture_module` follows the bare
    sibling-import convention documented in this module's docstring.

    `assertion_spec` is the chunk 4.3 dict (`must_call_tools`/
    `must_not_call_tools`/`max_steps`/`no_exception`/`rationale`/
    `semantic_rubric`), e.g. from a fetched run's
    `diagnosis["assertion_spec"]`. `None`/falsy renders chunk 4.2's
    original placeholder-assertion template instead — a run without a
    generated spec yet is the common case, not an error.
    """
    if not assertion_spec:
        return _TEST_TEMPLATE_NO_SPEC.format(
            run_id=run_id,
            run_id_slug=slugify_run_id(run_id),
            entrypoint=entrypoint,
            fixture_module=fixture_module,
        )

    return _TEST_TEMPLATE_WITH_SPEC.format(
        run_id=run_id,
        run_id_slug=slugify_run_id(run_id),
        entrypoint=entrypoint,
        fixture_module=fixture_module,
        rationale_comment=_render_rationale_comment(assertion_spec.get("rationale")),
        must_call_tools=list(assertion_spec.get("must_call_tools") or []),
        must_not_call_tools=list(assertion_spec.get("must_not_call_tools") or []),
        max_steps=assertion_spec.get("max_steps"),
        no_exception=bool(assertion_spec.get("no_exception", True)),
        output_checks=list(assertion_spec.get("output_checks") or []),
        semantic_rubric=assertion_spec.get("semantic_rubric"),
    )


def write_test_module(source: str, path: Union[str, Path]) -> Path:
    """Write already-rendered `source` to `path`, creating parent directories as needed.

    Warns to stderr (never blocks) if `path` already exists with different
    content (Day 4 audit: clobber-protection pending, resolved).
    """
    file_path = Path(path)
    file_path.parent.mkdir(parents=True, exist_ok=True)
    warn_if_overwriting_different_content(file_path, source)
    file_path.write_text(source)
    return file_path
